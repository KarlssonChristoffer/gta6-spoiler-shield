// Builds dist/gta6-spoiler-shield.user.js: the extension's content scripts
// plus the userscript menu, under a userscript header.
//
//   node scripts/build.mjs          write the file
//   node scripts/build.mjs --check  fail if the committed file is out of date
//
// The extension itself needs no build: load the extension/ folder as it is.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, bundle, manifest } from './lib/sources.mjs';

const { version, description, homepage_url: home } = manifest();
const OUT = join(ROOT, 'dist', 'gta6-spoiler-shield.user.js');
const RAW = home.replace('github.com', 'raw.githubusercontent.com') + '/main/dist/gta6-spoiler-shield.user.js';

const header = `// ==UserScript==
// @name         GTA 6 Spoiler Shield
// @namespace    ${home}
// @version      ${version}
// @description  ${description}
// @author       Claude Fable 5.2 (AI-generated code), directed by a human
// @license      MIT
// @homepageURL  ${home}
// @supportURL   ${home}/issues
// @downloadURL  ${RAW}
// @updateURL    ${RAW}
// @match        *://*/*
// @run-at       document-start
// @grant        GM_getValue
// @grant        GM_setValue
// @grant        GM_addValueChangeListener
// @grant        GM_registerMenuCommand
// ==/UserScript==

// This code was written by an AI (Claude Fable 5.2). Read it before you trust it.
//
// Generated by scripts/build.mjs from extension/src/. Do not edit this file:
// change the sources and run "npm run build".

`;

const output = header + bundle([join(ROOT, 'userscript', 'menu.js')]);

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== output) {
    console.error('dist/gta6-spoiler-shield.user.js is out of date. Run "npm run build" and commit the result.');
    process.exit(1);
  }
  console.log('dist is up to date');
} else {
  mkdirSync(join(ROOT, 'dist'), { recursive: true });
  writeFileSync(OUT, output);
  console.log(`built dist/gta6-spoiler-shield.user.js (v${version}, ${output.length} bytes)`);
}
